function inPoly(lon, lat, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/** 陸地上の [lon, lat] を格子サンプリングして返す。南極は帯として追加。 */
export function landPoints(step = 1.5) {
  const pts = [];
  for (let lat = -58; lat <= 80; lat += step) {
    for (let lon = -180; lon <= 180; lon += step) {
      for (const p of POLYS) {
        if (inPoly(lon, lat, p)) {
          pts.push([lon, lat]);
          break;
        }
      }
    }
  }
  // 南極（ポリゴンだと極付近で破綻するので帯で表現）
  for (let lat = -85; lat <= -64; lat += step) {
    for (let lon = -180; lon <= 180; lon += step * 1.4) pts.push([lon, lat]);
  }
  return pts;
}
